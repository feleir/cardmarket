// Turns the scraped shipping methods into the compact tiers the optimizer
// uses: { maxCards, maxValue, price, tracked }, cheapest first, without tiers
// another one beats (as cheap or cheaper, and at least as big).
const euro = (s) => Number(String(s).replace(/[^\d,]/g, '').replace(',', '.'));

// Cards per letter, from the help page: up to 20 g max. 4 cards, 50 g 17,
// 100 g 40. Heavier: about 2.2 g a card plus 13 g of packing, the same line.
export function cardsFor(grams) {
  if (grams <= 20) return 4;
  if (grams <= 50) return 17;
  if (grams <= 100) return 40;
  return Math.floor((grams - 13) / 2.17);
}

export function tiersOf(methods) {
  const tiers = (methods || []).filter((m) => !m.isVirtual && euro(m.price) > 0).map((m) => ({
    maxCards: cardsFor(m.maxWeight), maxValue: euro(m.maxValue), price: euro(m.price), tracked: !!m.isTracked,
  })).sort((a, b) => a.price - b.price || b.maxCards - a.maxCards || b.maxValue - a.maxValue);
  const kept = [];
  for (const t of tiers) {
    const beaten = kept.some((k) => k.price <= t.price && k.maxCards >= t.maxCards && k.maxValue >= t.maxValue && (k.tracked || !t.tracked));
    if (!beaten) kept.push(t);
  }
  return kept;
}

// Card orders never need parcels for more than ~1000 cards: those tiers are
// dropped except the cheapest, kept as the catch-all for a huge order.
export function forCards(tiers) {
  const small = tiers.filter((t) => t.maxCards <= 1000);
  const big = tiers.filter((t) => t.maxCards > 1000).sort((a, b) => a.price - b.price)[0];
  return big ? [...small, big] : small;
}

// Compact: every distinct tier list once (LISTS), and per seller country a
// row of list indexes by buyer country (-1: no shipping published).
export function buildTable(raw) {
  const ids = raw.countries.map((c) => c.id);
  const lists = [];
  const index = new Map();
  const matrix = ids.map((from) => ids.map((to) => {
    const t = forCards(tiersOf(raw.pairs[`${from}-${to}`]));
    if (!t.length) return -1;
    const key = JSON.stringify(t.map((x) => [x.maxCards, x.maxValue, x.price, x.tracked ? 1 : 0]));
    if (!index.has(key)) { index.set(key, lists.length); lists.push(key); }
    return index.get(key);
  }));
  return `// Generated by scripts/scrape-shipping.mjs from ${raw.source} on ${raw.scraped}.
// Do not edit: run \`npm run shipping\` to refresh.
// SHIPPING_MATRIX[i][j]: the tiers (an index into SHIPPING_LISTS) from seller
// country SHIPPING_COUNTRIES[i] to buyer country SHIPPING_COUNTRIES[j].
// A tier: [maxCards, maxValue, price, tracked].
export const SHIPPING_SCRAPED = '${raw.scraped}';
export const SHIPPING_COUNTRIES = ${JSON.stringify(ids)};
export const SHIPPING_LISTS = [
${lists.join(',\n')},
];
export const SHIPPING_MATRIX = [
${matrix.map((r) => JSON.stringify(r)).join(',\n')},
];
`;
}
